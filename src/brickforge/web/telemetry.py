"""Prometheus Telemetry, Latency Histograms & Health Monitoring for BrickForge.

Provides:
- REQUEST_LATENCY: Histogram of endpoint latencies across routes and HTTP methods.
- CHAT_TOKENS_GENERATED: Counter of output tokens produced by LFM3 / Ollama.
- VECTORS_INDEXED_TOTAL: Gauge for currently loaded FAISS dense vectors.
- FILES_SCANNED_TOTAL: Counter tracking ingested files across repositories.
- Fast, non-blocking middleware to record latency and HTTP status codes.
- Native `/metrics` export route without requiring external background ports.
"""

from __future__ import annotations

import time
from typing import Callable

from fastapi import FastAPI, Request, Response
from fastapi.responses import PlainTextResponse

try:
    from prometheus_client import (
        CONTENT_TYPE_LATEST,
        Counter,
        Gauge,
        Histogram,
        generate_latest,
    )
    PROMETHEUS_AVAILABLE = True
except ImportError:
    PROMETHEUS_AVAILABLE = False


if PROMETHEUS_AVAILABLE:
    # 1. Latency Histogram (Request time in seconds)
    REQUEST_LATENCY = Histogram(
        "brickforge_request_latency_seconds",
        "HTTP request execution latency in seconds",
        ["method", "endpoint", "status_code"],
        buckets=(0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0),
    )

    # 2. Ingestion Throughput Counters
    FILES_SCANNED_TOTAL = Counter(
        "brickforge_files_scanned_total",
        "Total source code files evaluated during ingestion",
        ["repository_id"],
    )

    BRICKS_EXTRACTED_TOTAL = Counter(
        "brickforge_bricks_extracted_total",
        "Total AST code bricks extracted into catalog",
        ["language", "kind"],
    )

    # 3. Vector & Model Performance Telemetry
    VECTORS_INDEXED_GAUGE = Gauge(
        "brickforge_vectors_indexed_total",
        "Current number of dense vectors loaded in the FAISS index",
    )

    CHAT_TOKENS_TOTAL = Counter(
        "brickforge_chat_tokens_total",
        "Total tokens generated by LLM / LFM3 models",
        ["model", "node"],
    )

    CHAT_TTFT_HISTOGRAM = Histogram(
        "brickforge_chat_ttft_seconds",
        "Time to first token (TTFT) for streaming responses",
        ["model", "node"],
        buckets=(0.05, 0.1, 0.2, 0.4, 0.8, 1.5, 3.0, 6.0),
    )
else:
    REQUEST_LATENCY = None
    FILES_SCANNED_TOTAL = None
    BRICKS_EXTRACTED_TOTAL = None
    VECTORS_INDEXED_GAUGE = None
    CHAT_TOKENS_TOTAL = None
    CHAT_TTFT_HISTOGRAM = None


def register_telemetry_middleware(app: FastAPI) -> None:
    """Register request timing and status code recording middleware."""
    if not PROMETHEUS_AVAILABLE:
        return

    @app.middleware("http")
    async def prometheus_telemetry_middleware(request: Request, call_next: Callable) -> Response:
        # Skip noisy polling or static assets if desired
        path = request.url.path
        if path.startswith("/static") or path == "/favicon.ico":
            return await call_next(request)

        t_start = time.perf_counter()
        try:
            response = await call_next(request)
            status_code = str(response.status_code)
        except Exception:
            status_code = "500"
            raise
        finally:
            elapsed = time.perf_counter() - t_start
            # Normalize route to avoid high cardinality
            norm_endpoint = path
            if path.startswith("/api/bricks/") and len(path.split("/")) > 3:
                norm_endpoint = "/api/bricks/{id}"
            elif path.startswith("/brickforge/api/bricks/") and len(path.split("/")) > 4:
                norm_endpoint = "/brickforge/api/bricks/{id}"

            REQUEST_LATENCY.labels(
                method=request.method,
                endpoint=norm_endpoint,
                status_code=status_code,
            ).observe(elapsed)

        return response


def get_metrics_response() -> Response:
    """Generate Prometheus exposition text for `/metrics`."""
    if not PROMETHEUS_AVAILABLE:
        return PlainTextResponse("# Prometheus client not installed\n", status_code=503)
    return Response(content=generate_latest(), media_type=CONTENT_TYPE_LATEST)
