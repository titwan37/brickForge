"""Composition provider interface and mock implementations for proposing code adaptations."""

from __future__ import annotations

import uuid
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional

from brickforge.composition.context import CompositionContext
from brickforge.composition.models import CompositionProposal, ProposalArtifact


@dataclass(frozen=True)
class ProviderMetadata:
    """Metadata regarding the generative or rule-based provider producing a proposal."""

    provider_name: str
    model_id: str
    version: str = "1.0"
    config: Dict[str, Any] = field(default_factory=dict)


class BaseCompositionProvider(ABC):
    """Abstract protocol for composition and adaptation providers.

    Keeps model and vendor details completely decoupled from core storage and indexing.
    """

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Name of the provider implementation."""

    @property
    @abstractmethod
    def model_id(self) -> str:
        """Model or engine identifier."""

    @abstractmethod
    def generate_proposal(self, context: CompositionContext) -> CompositionProposal:
        """Produce an adapted code proposal based on bounded context."""


class MockCompositionProvider(BaseCompositionProvider):
    """Deterministic mock provider for testing and offline development."""

    def __init__(
        self,
        provider_name: str = "mock_provider",
        model_id: str = "deterministic-v1",
        custom_generator: Optional[Callable[[CompositionContext], str]] = None,
    ):
        self._provider_name = provider_name
        self._model_id = model_id
        self._custom_generator = custom_generator

    @property
    def provider_name(self) -> str:
        return self._provider_name

    @property
    def model_id(self) -> str:
        return self._model_id

    def generate_proposal(self, context: CompositionContext) -> CompositionProposal:
        """Generate a deterministic proposal from composition context."""
        proposal_id = f"prop_mock_{uuid.uuid4().hex[:10]}"

        if self._custom_generator:
            code = self._custom_generator(context)
        else:
            # Assemble default proposed code from source bundles
            header = f"# Proposal generated by {self.provider_name} ({self.model_id})\n"
            header += f"# Target Language: {context.target_environment.language}\n"
            header += f"# Instructions: {context.adaptation_instructions}\n\n"

            bundle_codes = [b.get("source_code", "") for b in context.source_bundles]
            combined = "\n\n".join(bundle_codes)
            code = header + combined

        # Source bricks
        source_brick_ids = [b.get("brick_id", "") for b in context.source_bundles if b.get("brick_id")]

        # Primary artifact
        out_filename = "adapted_module.py"
        artifact = ProposalArtifact.create(file_path=out_filename, content=code)

        warnings: List[str] = []
        if context.is_truncated:
            warnings.append("Context was truncated; proposal was generated with partial context.")

        return CompositionProposal(
            proposal_id=proposal_id,
            request_id=context.request_id,
            adapted_code=code,
            source_brick_ids=source_brick_ids,
            status="draft",
            artifacts=[artifact],
            rationale=f"Automated adaptation following instructions: '{context.adaptation_instructions}'",
            confidence_score=0.90,
            warnings=warnings,
        )

